DECLARE FECHA_INICIO DATE DEFAULT DATE '2025-01-01';
DECLARE FECHA_FIN  DATE DEFAULT DATE '2026-06-30';
DECLARE COD_PRODUCTO  STRING DEFAULT '804';

WITH certificados_pagos AS (       
  SELECT CERTIFICADO, DATE(FECHA_DE_INICIO_DEL_SEGURO) AS FECHA_INICIO_ULT_PAGO, 
        DATE(FECHA_FIN_DEL_SEGURO) AS FECHA_FIN_ULT_PAGO,
        SUBSTR(TRAMA_ORIGINAL, 150, 1) AS TIPO_DOCUMENTO, 
        SUBSTR(TRAMA_ORIGINAL, 151, 10) AS NRO_DOCUMENTO,
        SUBSTR(TRAMA_ORIGINAL, 50, 20) AS APELLIDO_PATERINO, 
        SUBSTR(TRAMA_ORIGINAL, 80, 30) AS APELLIDO_MATERNO,
        SUBSTR(TRAMA_ORIGINAL, 110, 30) AS NOMBRES, DATE(FECHA_DE_AFILIACION) AS FECHA_AFILIACION,
        `produccion.FN_convertir_numero_trama`(SUBSTR(TRAMA_ORIGINAL, 397, 15)) AS MONTO_ASEGURADO,
        PRIMA_BRUTA
  FROM (
      SELECT *, ROW_NUMBER() OVER  (PARTITION BY CERTIFICADO ORDER BY FECHA_DE_INICIO_DEL_SEGURO DESC ) AS NRO
      FROM (
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2025`
        UNION ALL
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2026`
      )
      WHERE TIPO_DE_SEGURO = COD_PRODUCTO AND TIPO_DE_MOVIMIENTO IN ('4') AND
            FECHA_TRAMA BETWEEN FECHA_INICIO AND FECHA_FIN
  )
  WHERE NRO= 1
),
bajas AS(
  SELECT DISTINCT CERTIFICADO
  FROM (
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2025`
        UNION ALL
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2026`
      )
  WHERE TIPO_DE_SEGURO = COD_PRODUCTO AND TIPO_DE_MOVIMIENTO IN ('2','6') AND
        EXTRACT (YEAR FROM FECHA_TRAMA) = EXTRACT(YEAR FROM FECHA_FIN) AND 
        EXTRACT (MONTH FROM FECHA_TRAMA) = EXTRACT(MONTH FROM FECHA_FIN)
)
SELECT P.*, B.CERTIFICADO IS NOT NULL AS TIENE_BAJA
FROM certificados_pagos P
LEFT JOIN BAJAS B USING (CERTIFICADO)
