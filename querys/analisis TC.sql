CREATE OR REPLACE TABLE `produccion.TEMP_TRAMAS_diarias_TC_2022-2026` AS
  SELECT CERTIFICADO, 
        DATE(FECHA_DE_INICIO_DEL_SEGURO) AS FECHA_INICIO, 
        DATE(FECHA_DE_AFILIACION) AS FECHA_AFILIACION, 
        DATE(FECHA_DECLARADA) AS FECHA_RECEPCION, 
        SUBSTR(TRAMA_ORIGINAL, 151, 10) AS NUMERO_DOC, 
        TIPO_DE_MOVIMIENTO, MONEDA, PRIMA_BRUTA,
        `produccion.FN_convertir_numero_trama`(SUBSTR(TRAMA_ORIGINAL, 397, 15)) AS MONTO_ASEGURADO,
        SAFE_CAST(SUBSTR(TRAMA_ORIGINAL, 433, 10) AS INT64) / 10000000 AS TASA,
        SUBSTR(TRAMA_ORIGINAL, 480, 6) AS TIPO_BIN, SUBSTR(TRAMA_ORIGINAL, 486, 2) AS MULTI_BIN
  FROM (
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2022`
        UNION ALL
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2023`
        UNION ALL
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2024`
        UNION ALL
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2025`
        UNION ALL
        SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2026`
  )
  WHERE TIPO_DE_SEGURO ='918' AND TIPO_DE_MOVIMIENTO IN ('1','4') AND TIPO_DE_REGISTRO = '01';



CREATE OR REPLACE TABLE `produccion.TEMP_TRAMAS_diarias_TC_2022-2026_ALTAS` AS
SELECT a.*, p.PRIMA_BRUTA AS PRIMA_PAGO
FROM `produccion.TEMP_TRAMAS_diarias_TC_2022-2026` a
JOIN `produccion.TEMP_TRAMAS_diarias_TC_2022-2026` p ON a.CERTIFICADO = p.CERTIFICADO
        AND a.FECHA_RECEPCION = p.FECHA_RECEPCION
WHERE a.TIPO_DE_MOVIMIENTO = '1' AND p.TIPO_DE_MOVIMIENTO = '4';

------------------------ CONTEO DE ALTAS POR FECHA RECEPCION ----------------------

WITH altas_cumplimiento AS(
  SELECT
    *,
    CASE
      WHEN FECHA_RECEPCION < DATE '2022-05-20' THEN
      CASE
        WHEN TASA = 0 THEN 'SIN TASA'
        ELSE 'CON TASA'
      END
      WHEN FECHA_RECEPCION >= DATE '2022-05-20' THEN
      CASE
        WHEN TASA > 0 THEN 'CON TASA'
        ELSE 'SIN TASA'
      END
    END AS CUMPLIMIENTO
  FROM `produccion.TEMP_TRAMAS_diarias_TC_2022-2026_ALTAS`
)
SELECT 
  CASE
    WHEN FECHA_RECEPCION < DATE '2022-05-20' THEN 'ANTES 20_MAYO_2022'
    ELSE 'DESPUES 20_MAYO_2022'
  END AS PERIODO, EXTRACT(YEAR FROM FECHA_RECEPCION) AS YEAR, EXTRACT(MONTH FROM FECHA_RECEPCION) AS MES,
CUMPLIMIENTO, COUNT(*) AS CANTIDAD
FROM altas_cumplimiento
GROUP BY PERIODO, YEAR, MES, CUMPLIMIENTO
ORDER BY PERIODO, YEAR, MES, CUMPLIMIENTO;

