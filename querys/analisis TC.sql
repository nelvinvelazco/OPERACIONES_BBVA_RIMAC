        FORMAT('%.2f',SUM(PRIMA_CALCULADA)) AS TOTAL_PRIMA_CALCULADA,
        FORMAT('%.2f',SUM(PRIMA_BRUTA) - SUM(PRIMA_CALCULADA)) AS DIFERENCIA,
