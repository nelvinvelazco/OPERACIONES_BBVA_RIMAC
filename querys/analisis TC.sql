-------------- DIFERENCIA DE PRIMA_BRUTA Y PRIMA CALCULADA DE PRIMEROS PAGOS ALTAS ----------------------------

WITH base AS(
  SELECT CERTIFICADO, FECHA_INICIO, FECHA_RECEPCION, TIPO_DE_MOVIMIENTO, MONEDA, PRIMA_BRUTA,
      TASA,MONTO_ASEGURADO, PRIMA_PAGO,
    CASE
      WHEN FECHA_RECEPCION >= DATE '2022-05-20' THEN
        CASE
          WHEN TASA > 0 THEN  
            CASE
              WHEN MONEDA = 'PEN' AND ROUND((MONTO_ASEGURADO * TASA / 100),2) > 20.0 THEN 20.0
              WHEN MONEDA = 'USD' AND ROUND((MONTO_ASEGURADO * TASA / 100),2) > 5.5 THEN 5.5
              ELSE ROUND((MONTO_ASEGURADO * TASA / 100),2)
            END 
          ELSE PRIMA_PAGO
        END
      ELSE PRIMA_PAGO
    END AS PRIMA_CALCULADA
  FROM `produccion.TEMP_TRAMAS_diarias_TC_2022-2026_ALTAS`
  #WHERE CERTIFICADO = '00110257334000280554'
)
SELECT EXTRACT(YEAR FROM FECHA_RECEPCION) AS ANIO, EXTRACT(MONTH FROM FECHA_RECEPCION) AS MES,  
        FORMAT("%.2f",SUM(PRIMA_PAGO)) AS TOTAL_PRIMA_BRUTA, 
        FORMAT('%.2f',SUM(PRIMA_CALCULADA)) AS TOTAL_PRIMA_CALCULADA
FROM base
GROUP BY ANIO, MES
ORDER BY ANIO, MES;

--------------------- DIFERENCIA DE PRIMA_BRUTA Y PRIMA CALCULADA DE PAGOS ------------------------------

CREATE OR REPLACE TABLE `produccion.TEMP_TRAMAS_diarias_TC_2022-2026_CON_CALCULO` AS
WITH base AS(
  SELECT CERTIFICADO, FECHA_RECEPCION, FECHA_INICIO, MONEDA, PRIMA_BRUTA,
      TASA, MONTO_ASEGURADO, 
    CASE
      WHEN FECHA_RECEPCION >= DATE '2022-05-20' THEN
        CASE
          WHEN TASA > 0 THEN  
            CASE
              WHEN MONEDA = 'PEN' AND ROUND((MONTO_ASEGURADO * TASA / 100),2) > 20.0 THEN 20.0
              WHEN MONEDA = 'USD' AND ROUND((MONTO_ASEGURADO * TASA / 100),2) > 5.5 THEN 5.5
              ELSE ROUND((MONTO_ASEGURADO * TASA / 100),2)
            END 
          ELSE 
            CASE
              WHEN MONEDA = 'PEN' AND ROUND((MONTO_ASEGURADO * 0.256 / 100),2) > 20.0 THEN 20.0
              WHEN MONEDA = 'USD' AND ROUND((MONTO_ASEGURADO * 0.256 / 100),2) > 5.5 THEN 5.5
              ELSE ROUND((MONTO_ASEGURADO * 0.256 / 100),2)
            END
        END
      ELSE PRIMA_BRUTA
    END AS PRIMA_CALCULADA
  FROM `produccion.TEMP_TRAMAS_diarias_TC_2022-2026`
  WHERE TIPO_DE_MOVIMIENTO = '4'
)
SELECT *,
    CASE
      WHEN PRIMA_CALCULADA = PRIMA_BRUTA THEN 'IGUAL'
      WHEN PRIMA_CALCULADA < PRIMA_BRUTA AND TASA = 0 THEN 'MENOR - SIN TASA'
      WHEN PRIMA_CALCULADA < PRIMA_BRUTA AND TASA > 0 THEN 'MENOR - CON TASA'
      WHEN PRIMA_CALCULADA > PRIMA_BRUTA AND TASA = 0 THEN 'MAYOR - SIN TASA'
      WHEN PRIMA_CALCULADA > PRIMA_BRUTA AND TASA > 0 THEN 'MAYOR - CON TASA'
    END AS CAT_PRIMA
FROM base;
