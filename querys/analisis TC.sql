    )
WHERE NRO= 1
)
SELECT EXTRACT(YEAR FROM FECHA_RECEPCION) AS ANIO, EXTRACT(MONTH FROM FECHA_RECEPCION) AS MES, COUNT(*) AS CANTIDAD, #CAT_PRIMA
