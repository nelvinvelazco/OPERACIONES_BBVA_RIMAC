------------------------------- PRIMA DOLARIZADA DE TRAMAS SUSTENTO -------------------------------
WITH TOTALES AS(
  SELECT EXTRACT(YEAR FROM T.fecha_recepcion) AS YEAR, EXTRACT(MONTH FROM T.fecha_recepcion) AS MES,
          CASE
            WHEN Codigo_Subproducto IN ('901','902','903','906','941','951',
                                  '952','953','954','958','959','961',
                                  '962','963','964','966','968','972') THEN 'PRESTAMOS'
            ELSE Codigo_Subproducto
          END AS COD_PRODUCTO, 
          CASE
            WHEN Codigo_Subproducto IN ('901','902','903','906','941','951',
                                  '952','953','954','958','959','961',
                                  '962','963','964','966','968','972') THEN 'DESGRAVAMEN PRESTAMOS'
            ELSE E.PRODUCTO
          END AS NOMBRE_PRODUCTO,
          MONEDA,  COUNT(*) AS CANTIDAD,SUM(Prima) AS TOTAL_PRIMA
  FROM `develop.TABLA_SUSTENTO_BBVA` T
  LEFT JOIN `produccion.EQUIVALENCIAS_PRODUCTOS` E ON T.Codigo_Subproducto= E.CODIGO_PRODUCTO
  WHERE fecha_recepcion BETWEEN '2026-09-01' AND '2026-09-30'
  GROUP BY YEAR, MES, COD_PRODUCTO,NOMBRE_PRODUCTO, MONEDA
  ORDER BY YEAR, MES, COD_PRODUCTO
),
DOLARIZADO AS(
  SELECT T.*, 
    CASE WHEN COD_PRODUCTO IN ('805','807','703','803_TLMK','804','809','812','816','825','827',
                                '829','904','905','907','909','919','970') 
          THEN TOTAL_PRIMA /1.18
          ELSE TOTAL_PRIMA 
    END AS PRIMA_SIN_IGV,
    CASE WHEN COD_PRODUCTO IN ('805','807','703','803_TLMK','804','809','812','816','825','827',
                                '829','904','905','907','909','919','970')
        THEN 
            CASE WHEN MONEDA IN ('PEN','VAC')
                    THEN (TOTAL_PRIMA /1.18)/3.433
                    ELSE (TOTAL_PRIMA /1.18)
            END
    ELSE 
        CASE WHEN MONEDA IN ('PEN','VAC')
              THEN (TOTAL_PRIMA/3.433)
              ELSE TOTAL_PRIMA
        END
    END AS PRIMA_COMERCIAL, 3.433 AS TIPO_CAMBIO
  FROM TOTALES T
  LEFT JOIN `produccion.TIPO_CAMBIO_DOLAR` D ON CONCAT(T.YEAR,LPAD(CAST(MES AS STRING), 2, '0'))= D.PERIODO
)
SELECT *
FROM DOLARIZADO
ORDER BY YEAR, MES, COD_PRODUCTO


