  GROUP BY YEAR, MES, COD_PRODUCTO,NOMBRE_PRODUCTO, MONEDA
  ORDER BY YEAR, MES, COD_PRODUCTO
),
DOLARIZADO AS(
  SELECT T.*, 
    CASE WHEN COD_PRODUCTO IN ('805','807','703','803_TLMK','804','809','812','816','825','827',
                                '829','904','905','907','909','919','970')
          THEN TOTAL_PRIMA /1.18
          ELSE TOTAL_PRIMA 
    END AS PRIMA_SIN_IGV,
    CASE WHEN COD_PRODUCTO IN ('805','807','703','803_TLMK','804','809','812','816','825','827',
                                '829','904','905','907','909','919','970')
        THEN 
            CASE WHEN MONEDA IN ('PEN','VAC')
                    THEN (TOTAL_PRIMA /1.18)/D.CAMBIO
                    ELSE (TOTAL_PRIMA /1.18)
            END
