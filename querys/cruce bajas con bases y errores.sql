WITH bajas_tramas AS (
  SELECT DISTINCT CERTIFICADO, TIPO_DE_SEGURO AS CODIGO_PRODUCTO, TIPO_DE_MOVIMIENTO, TIPO_DE_REGISTRO, 
        REGEXP_REPLACE(TRAMA_ORIGINAL, r'[^\x20-\x7E\n\r]|\t', ' ') AS TRAMA_LIMPIA,
        DATE (FECHA_TRAMA) AS FECHA_TRAMA,
        CONCAT(SUBSTR(CERTIFICADO, 1,4),SUBSTR(CERTIFICADO, 7,2), SUBSTR(CERTIFICADO, 11,10)) AS CERT_CRUCE
  FROM `produccion.TRAMAS_diarias_BBVA_2026`
  WHERE TIPO_DE_MOVIMIENTO IN ('2','6') AND
      FECHA_TRAMA BETWEEN '2026-10-01' AND '2026-10-31' AND
      TIPO_DE_SEGURO = '919'
),
bases AS (
  SELECT TRIM(CERTIFICADO_BANCO) AS CERTIFICADO_BASE, FECHA_OPERACION, PRIMA,
        CONCAT(SUBSTR(TRIM(CERTIFICADO_BANCO), 1,4),SUBSTR(TRIM(CERTIFICADO_BANCO), 7,2), 
                  SUBSTR(TRIM(CERTIFICADO_BANCO), 11,10)) AS CERT_CRUCE_BASE
        
  FROM `produccion.BASES_CONCILIACION`
),
errores AS (
  SELECT DISTINCT COD_DE_CERTIFICADO,
          CONCAT(SUBSTR(COD_DE_CERTIFICADO, 1,4),SUBSTR(COD_DE_CERTIFICADO, 7,2), SUBSTR(COD_DE_CERTIFICADO, 11,10)) AS CERT_CRUCE_ERROR
  FROM `produccion.ERRORES_BBVA_desgravamen_TKT`
  #FROM `produccion.ERRORES_BBVA_desgravamen_TC`
)
SELECT DISTINCT T.CERTIFICADO, T.CODIGO_PRODUCTO, P.PRODUCTO, T.TIPO_DE_MOVIMIENTO, 
        TIPO_DE_REGISTRO, T.TRAMA_LIMPIA, FECHA_TRAMA
FROM bajas_tramas T
LEFT JOIN bases B ON T.CERT_CRUCE = B.CERT_CRUCE_BASE
LEFT JOIN errores E ON T.CERTIFICADO= E.CERT_CRUCE_ERROR
LEFT JOIN `produccion.EQUIVALENCIAS_PRODUCTOS` P ON T.CODIGO_PRODUCTO= P.CODIGO_PRODUCTO
WHERE B.CERTIFICADO_BASE IS NULL AND E.COD_DE_CERTIFICADO IS NULL


